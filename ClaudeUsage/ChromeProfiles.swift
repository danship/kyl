import Foundation

// Chrome's profiles and each one's theme color, so an account can wear the
// color of the Chrome profile it's signed into there.
//
// These are Chrome's private files, not an API: Local State lists the
// profiles, each profile's Preferences names its theme, and a Web Store
// theme's manifest declares its colors. Google can change any of them, so
// every read fails soft — a theme that can't be read leaves an account the
// color it already has.
//
// Nonisolated: it only reads files and computes, so nothing in it belongs to
// the main actor the rest of the app defaults to.
nonisolated enum ChromeProfiles {
    struct Profile: Identifiable, Equatable {
        let id: String          // the profile's folder, e.g. "Profile 2"
        let name: String
        let email: String?

        var label: String { email.map { "\(name) (\($0))" } ?? name }
    }

    enum Theme: Equatable {
        case color(String)      // "#RRGGBB"
        case none               // Chrome's default look: no color to wear
        case unreadable
    }

    static let root = FileManager.default.homeDirectoryForCurrentUser
        .appendingPathComponent("Library/Application Support/Google/Chrome", isDirectory: true)

    static func profiles() -> [Profile] {
        guard let state = json(root.appendingPathComponent("Local State")),
              let cache = (state["profile"] as? [String: Any])?["info_cache"] as? [String: [String: Any]]
        else { return [] }
        return cache.map { folder, info in
            let email = (info["user_name"] as? String).flatMap { $0.isEmpty ? nil : $0 }
            return Profile(id: folder, name: info["name"] as? String ?? folder, email: email)
        }
        .sorted { $0.id.localizedStandardCompare($1.id) == .orderedAscending }
    }

    static func theme(ofProfile folder: String) -> Theme {
        let profileDir = root.appendingPathComponent(folder, isDirectory: true)
        guard let prefs = json(profileDir.appendingPathComponent("Preferences")) else { return .unreadable }
        return theme(preferences: prefs) { id, pack in
            // The unpacked theme lives where Preferences says; failing that,
            // in the newest version folder under the profile's Extensions.
            let packDir = pack.map { URL(fileURLWithPath: $0, isDirectory: true) } ?? {
                let versions = profileDir.appendingPathComponent("Extensions/\(id)", isDirectory: true)
                let newest = (try? FileManager.default.contentsOfDirectory(atPath: versions.path))?
                    .sorted { $0.localizedStandardCompare($1) == .orderedAscending }.last
                return newest.map { versions.appendingPathComponent($0, isDirectory: true) }
            }()
            return packDir.flatMap { json($0.appendingPathComponent("manifest.json")) }
        }
    }

    // Which theme a profile wears, in Chrome's own order of precedence: an
    // installed theme, then a color generated from one, then a color picked in
    // Chrome's Customize panel, else the default look. `manifest` loads an
    // installed theme's manifest from its id and unpacked folder.
    static func theme(preferences prefs: [String: Any],
                      manifest: (_ id: String, _ pack: String?) -> [String: Any]?) -> Theme {
        let installed = (prefs["extensions"] as? [String: Any])?["theme"] as? [String: Any] ?? [:]
        let browserTheme = (prefs["browser"] as? [String: Any])?["theme"] as? [String: Any] ?? [:]
        let id = installed["id"] as? String ?? ""

        switch id {
        case "autogenerated_theme_id":
            let generated = (prefs["autogenerated"] as? [String: Any])?["theme"] as? [String: Any]
            guard let argb = generated?["color"] as? Int else { return .unreadable }
            return .color(RGB(argb: argb).hex)
        case "", "user_color_theme_id":
            // Newer builds keep a synced copy of the picked color under a "2"
            // name; it's the one Chrome reads when both are there.
            if let argb = (browserTheme["user_color2"] ?? browserTheme["user_color"]) as? Int {
                return .color(RGB(argb: argb).hex)
            }
            return .none
        default:
            guard let manifest = manifest(id, installed["pack"] as? String) else { return .unreadable }
            let colors = (manifest["theme"] as? [String: Any])?["colors"] as? [String: Any] ?? [:]
            let pick = identityColor(frame: colors["frame"].flatMap { RGB(manifestValue: $0) },
                                     toolbar: colors["toolbar"].flatMap { RGB(manifestValue: $0) })
            // A theme drawn entirely from images declares no colors to wear.
            return pick.map { .color($0.hex) } ?? .none
        }
    }

    // One color for the account from a theme's several: the more vivid of the
    // toolbar (around the address bar and the active tab) and the frame (the
    // tab strip), by HSL saturation. Near-black and near-white are a theme's
    // backdrop rather than its color, so they only win when nothing else is
    // there. Ties go to the toolbar, the larger band.
    static func identityColor(frame: RGB?, toolbar: RGB?) -> RGB? {
        func score(_ c: RGB) -> Double { c.isBackdrop ? -1 : c.saturation }
        switch (toolbar, frame) {
        case let (t?, f?): return score(f) > score(t) ? f : t
        case let (t?, nil): return t
        case let (nil, f?): return f
        case (nil, nil): return nil
        }
    }

    struct RGB: Equatable {
        let r: Double, g: Double, b: Double     // 0…1

        init(r: Double, g: Double, b: Double) { self.r = r; self.g = g; self.b = b }

        // Chrome stores picked colors as signed 32-bit ARGB.
        init(argb: Int) {
            let v = argb & 0xFFFFFF
            self.init(r: Double((v >> 16) & 0xFF) / 255, g: Double((v >> 8) & 0xFF) / 255,
                      b: Double(v & 0xFF) / 255)
        }

        // A manifest color is [r, g, b] or [r, g, b, alpha], channels 0…255.
        init?(manifestValue: Any) {
            guard let parts = manifestValue as? [NSNumber], parts.count >= 3 else { return nil }
            self.init(r: parts[0].doubleValue / 255, g: parts[1].doubleValue / 255,
                      b: parts[2].doubleValue / 255)
        }

        var lightness: Double { (max(r, g, b) + min(r, g, b)) / 2 }
        var saturation: Double {
            let chroma = max(r, g, b) - min(r, g, b)
            let l = lightness
            return chroma == 0 ? 0 : chroma / (1 - abs(2 * l - 1))
        }
        var isBackdrop: Bool { lightness < 0.12 || lightness > 0.92 }

        var hex: String {
            func byte(_ v: Double) -> Int { Int((min(max(v, 0), 1) * 255).rounded()) }
            return String(format: "#%02X%02X%02X", byte(r), byte(g), byte(b))
        }
    }

    // Chrome's manifests may carry comments and trailing commas, which JSON5
    // parsing accepts.
    private static func json(_ url: URL) -> [String: Any]? {
        guard let data = try? Data(contentsOf: url) else { return nil }
        return (try? JSONSerialization.jsonObject(with: data, options: [.json5Allowed])) as? [String: Any]
    }
}
